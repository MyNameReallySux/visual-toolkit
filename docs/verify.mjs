/**
 * End-to-end checks for the Starlight docs site.
 *
 * Usage:
 *   node verify.mjs                  # against http://localhost:4321 (astro dev)
 *   BASE=http://localhost:4322 node verify.mjs   # against astro preview
 */
import { chromium } from "playwright";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const BASE = process.env.BASE ?? "http://localhost:4321";
const SCREENSHOTS = path.join(__dirname, "screenshots");

/**
 * Per-page expectations.
 * - svgs: minimum number of rendered demo SVGs
 * - sliders: minimum number of range inputs (composing must have NONE)
 * - usage: expect an always-visible usage code block
 * - fullSource: expect a collapsed <details class="full-source">
 */
const PAGES = [
  { path: "/", svgs: 0, sliders: 0, usage: true, fullSource: false },
  { path: "/band-scales/introduction/", svgs: 1, usage: true, fullSource: true },
  { path: "/band-scales/margins-gaps/", svgs: 3, sliders: 1, usage: true, fullSource: true },
  { path: "/band-scales/fixed/", svgs: 1, sliders: 3, usage: true, fullSource: true },
  { path: "/band-scales/dynamic/", svgs: 1, sliders: 1, usage: true, fullSource: true },
  { path: "/band-scales/enum/", svgs: 1, sliders: 1, usage: true, fullSource: true },
  { path: "/band-scales/grid-layout/", svgs: 1, sliders: 1, usage: true, fullSource: true },
  { path: "/band-scales/composing/", svgs: 1, sliders: 0, noSliders: true, usage: true, fullSource: true },
  { path: "/band-scales/transform-fit/", svgs: 2, sliders: 3, usage: true, fullSource: true },
  { path: "/discontinuous/timeline/", svgs: 3, sliders: 3, usage: true, fullSource: true },
  { path: "/helpers/band-math/", svgs: 1, sliders: 1, usage: true, fullSource: true },
  { path: "/helpers/svg-helpers/", svgs: 1, sliders: 1, usage: true, fullSource: true },
  { path: "/helpers/select-or-create/", svgs: 1, button: true, usage: true, fullSource: true },
  { path: "/helpers/css-numbers/", svgs: 1, usage: true, fullSource: true },
];

/** API reference pages generated by starlight-typedoc. */
const API_PAGES = [
  "/api/",
  "/api/visual-toolkit/d3-band-scales/",
  "/api/visual-toolkit/d3-discontinuous-scale/",
  "/api/visual-toolkit/d3-helpers/",
];

async function run() {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage();
  await page.setViewportSize({ width: 1280, height: 900 });

  const failures = [];

  for (const spec of PAGES) {
    await page.goto(BASE + spec.path, { waitUntil: "networkidle" });
    await page.waitForTimeout(300);

    const r = await page.evaluate(() => ({
      svgs: document.querySelectorAll(".demo-card svg, .svg-canvas svg").length,
      sliders: document.querySelectorAll("input[type=\"range\"]").length,
      buttons: document.querySelectorAll(".demo-card button").length,
      usageBlocks: document.querySelectorAll(".expressive-code").length,
      fullSource: Array.from(document.querySelectorAll("details.full-source")).map((d) => d.open),
      title: document.title,
      highlighted: document.querySelectorAll(".expressive-code span[style], .expressive-code [class*='tok']").length,
    }));

    const errs = [];
    if (r.svgs < spec.svgs) errs.push(`expected >=${spec.svgs} demo SVGs, got ${r.svgs}`);
    if (spec.noSliders && r.sliders > 0) errs.push(`expected NO sliders, got ${r.sliders}`);
    if (!spec.noSliders && spec.sliders && r.sliders < spec.sliders)
      errs.push(`expected >=${spec.sliders} sliders, got ${r.sliders}`);
    if (spec.button && r.buttons < 1) errs.push("expected a demo button");
    if (spec.usage && r.usageBlocks < 1) errs.push("no usage code block");
    if (spec.usage && r.highlighted < 4) errs.push("usage code block not syntax-highlighted");
    if (spec.fullSource) {
      if (r.fullSource.length < 1) errs.push("no full-source <details>");
      if (r.fullSource.some((open) => open)) errs.push("full-source <details> should start collapsed");
    }

    console.log(`[page] ${spec.path}: ${errs.length === 0 ? "PASS" : `FAIL — ${errs.join("; ")}`}`);
    for (const e of errs) failures.push(`${spec.path}: ${e}`);
  }

  for (const apiPath of API_PAGES) {
    const resp = await page.goto(BASE + apiPath, { waitUntil: "domcontentloaded" });
    const ok = resp && resp.status() === 200;
    const hasContent = ok && (await page.locator(".sl-markdown-content").count()) > 0;
    console.log(`[api] ${apiPath}: ${ok && hasContent ? "PASS" : "FAIL"}`);
    if (!ok || !hasContent) failures.push(`${apiPath}: missing or empty`);
  }

  // Screenshots of the composing page (the regression-prone demo) at 3 widths
  for (const width of [1024, 1280, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await page.goto(BASE + "/band-scales/composing/", { waitUntil: "networkidle" });
    await page.waitForTimeout(300);
    await page.screenshot({ path: path.join(SCREENSHOTS, `composing-${width}.png`), fullPage: true });
  }
  console.log("[screenshot] composing-{1024,1280,1440}.png saved");

  await browser.close();

  console.log("\n=== SUMMARY ===");
  if (failures.length === 0) {
    console.log("All checks PASSED.");
  } else {
    console.log(`${failures.length} failure(s):`);
    failures.forEach((f) => console.log(`  - ${f}`));
    process.exit(1);
  }
}

run().catch((err) => {
  console.error(err);
  process.exit(1);
});
